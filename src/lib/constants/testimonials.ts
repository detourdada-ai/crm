/**
 * 실사용 후기 데이터 (LANDING v5, 2026-09-07).
 *
 * ⚠️ **여기에는 실제로 들은 말만 넣는다.**
 *
 * 사장님이 하지 않은 말을 만들어 "실사용 후기"로 공개하는 것은 허위 표시다.
 * 그래서 이 배열은 **비어 있는 상태로 시작하고, 비어 있으면 랜딩에 후기 섹션이
 * 아예 렌더되지 않는다**(TestimonialsSection이 null을 반환한다). 카드·별점·슬라이드
 * UI는 이미 완성돼 있으므로, 실제 후기를 확보하면 **이 파일에 항목만 추가하면**
 * 바로 노출된다. 코드 수정은 필요 없다.
 *
 * 채우는 규칙:
 * - `quote`  : 들은 말을 그대로. 다듬더라도 의미를 바꾸지 않는다. 2~3줄 분량.
 * - `author` : 실명 금지. 업종 + 호칭까지만(예: "반찬가게 대표", "밑반찬 전문점 사장님").
 * - `rating` : 실제로 받은 별점만. 물어보지 않았으면 `undefined`로 두면 별이 표시되지 않는다.
 * - 성과 수치("30분이면 끝나요", "매출 2배")는 **당사자가 직접 말한 경우에만** 인용에 남긴다.
 *   우리가 계산해서 붙이지 않는다.
 *
 * 수집 경로: STEP14 실사용 테스트에서 나온 사장님들의 실제 발언
 * (`docs/product/STEP14-DISCOVERY-LOG.md`).
 */
export interface Testimonial {
  quote: string;
  /** 업종 + 호칭. 실명·상호명·전화번호는 넣지 않는다. */
  author: string;
  /** 1~5. 실제로 받은 값만. 없으면 비워 둔다. */
  rating?: number;
}

